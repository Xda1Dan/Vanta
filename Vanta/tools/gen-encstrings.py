#!/usr/bin/env python3
"""
Encrypts the Lua bootstrap blobs in src/RBX/environment/Lua/*.lua into
src/RBX/environment/EncStrings.h so the shipped dylib carries no plaintext Lua.
Each blob is XORed with a splitmix64 keystream (per-blob seed); the C++ side
reproduces the same stream to decrypt once at load. `strings` on the binary
then shows nothing of the bootstrap.

This is Layer A of the obfuscation - it defeats casual inspection on its own and
is the floor beneath the O-MVLL pass (Layer B), which then hides the decryptor.
"""
import glob, os, re, sys

MASK = (1 << 64) - 1
import os as _os
MASTER = int(_os.environ.get("NEXA_ENC_MASTER", "0xA17C9E3B5D2F4188"), 16) & MASK  # publish.sh rotates this per release

def fnv1a(b):
    h = 0xcbf29ce484222325
    for c in b: h = ((h ^ c) * 0x100000001b3) & MASK
    return h

def stream(seed, n):
    s = seed & MASK
    out = bytearray(n)
    for i in range(n):
        s = (s + 0x9E3779B97F4A7C15) & MASK
        z = s
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        z = (z ^ (z >> 31)) & MASK
        out[i] = z & 0xFF
    return out

def seed_for(name):
    return (fnv1a(name.encode()) ^ MASTER) & MASK

def octal_lit(data, width=24):
    lines, i = [], 0
    while i < len(data):
        chunk = data[i:i+width]
        lines.append('"' + "".join("\\%03o" % b for b in chunk) + '"')
        i += width
    return lines

def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    files = sorted(glob.glob(os.path.join(root, "src", "RBX", "environment", "Lua", "*.lua")))
    out = ['//', '//  EncStrings.h  (generated by tools/gen-encstrings.py - do not edit)',
           '//', '#pragma once', '#include <string>', '#include <cstdint>', '#include <cstddef>',
           '', 'namespace vantastr {', '',
           'inline std::string decrypt(const char* data, size_t n, uint64_t seed) {',
           '    std::string out; out.resize(n);',
           '    uint64_t s = seed;',
           '    for (size_t i = 0; i < n; ++i) {',
           '        s += 0x9E3779B97F4A7C15ULL;',
           '        uint64_t z = s;',
           '        z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ULL;',
           '        z = (z ^ (z >> 27)) * 0x94D049BB133111EBULL;',
           '        z =  z ^ (z >> 31);',
           '        out[i] = (char)((unsigned char)data[i] ^ (unsigned char)(z & 0xFF));',
           '    }',
           '    return out;',
           '}', '']
    for f in files:
        name = re.sub(r'[^A-Za-z0-9_]', '_', os.path.splitext(os.path.basename(f))[0])
        plain = open(f, "rb").read()
        seed = seed_for(name)
        ks = stream(seed, len(plain))
        cipher = bytes(p ^ k for p, k in zip(plain, ks))
        # self-check
        back = bytes(c ^ k for c, k in zip(cipher, stream(seed, len(cipher))))
        assert back == plain, "round-trip failed for " + name
        out.append('// %s (%d bytes)' % (name, len(plain)))
        out.append('inline const char kEnc_%s[] =' % name)
        out.extend('    ' + ln for ln in octal_lit(cipher))
        out[-1] += ';'
        out.append('inline constexpr size_t kEncLen_%s = %d;' % (name, len(plain)))
        out.append('inline constexpr uint64_t kSeed_%s = 0x%016XULL;' % (name, seed))
        out.append('inline std::string %s() { return decrypt(kEnc_%s, kEncLen_%s, kSeed_%s); }'
                   % (name, name, name, name))
        out.append('')
    out.append('} // namespace vantastr')
    dst = os.path.join(root, "src", "RBX", "environment", "EncStrings.h")
    open(dst, "w").write("\n".join(out) + "\n")
    print("wrote EncStrings.h for: " + ", ".join(re.sub(r'[^A-Za-z0-9_]','_',os.path.splitext(os.path.basename(f))[0]) for f in files))

if __name__ == "__main__":
    main()
