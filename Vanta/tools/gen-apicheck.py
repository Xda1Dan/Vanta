#!/usr/bin/env python3
"""Generate tests/apicheck.lua — the editor's tables, checked against the engine.

The editor's member tables come from Roblox's *documentation* (creator-docs),
not from the API dump: the dump describes classes and enums, and knows nothing
about `math`, `string`, `Vector3.zero` or `CFrame.identity`. Documentation is
written by people and is not the engine, so a member that exists and is not
documented becomes a squiggle under working code.

This emits a probe that asks the engine directly, in both directions:

    missing  — the engine has it, api.js does not   → a false positive
    extra    — api.js has it, the engine does not   → a typo we would not catch

The probe writes its answer to the workspace as JSON; tools/gen-apicheck.py
--compare reads it back and prints the two lists.

    python3 tools/gen-apicheck.py                 write tests/apicheck.lua
    ./tests/run.sh tests/apicheck.lua APICHECK    run it in a live game
    python3 tools/gen-apicheck.py --compare       read the answer

The answer is written by the probe into Vanta's workspace directory, which is
where --compare reads it from. The tables being compared belonged to the old
Monaco editor (gui/); the active SwiftUI app has no completion tables, so this
tool only runs if those tables exist.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
API_JS = os.path.join(ROOT, "gui", "Resources", "monaco", "api.js")
GLOBALS_JS = os.path.join(ROOT, "gui", "Resources", "monaco", "globals.js")
PROBE = os.path.join(ROOT, "tests", "apicheck.lua")
ANSWER = os.path.expanduser("~/Documents/Vanta/workspace/vanta-apicheck.json")


def load_tables():
    """The two generated tables, read the way jsc reads them."""
    text = open(API_JS, encoding="utf-8").read()
    inner = text[text.index('JSON.parse("') + len('JSON.parse("'):text.rindex('")')]
    api = json.loads(json.loads('"' + inner + '"'))

    text = open(GLOBALS_JS, encoding="utf-8").read()
    glob = json.loads(text[text.index("{"):text.rindex("}") + 1])
    return api, glob


def expected(api, glob):
    """What the editor believes each namespace holds — exactly what
    Resolver.hasMember answers with, including the executor union."""
    out = {}
    for name, lib in api["libraries"].items():
        members = [row[0] for row in lib.get("props", [])]
        members += [row[0] for row in lib.get("funcs", [])]
        members += glob["libraries"].get(name, [])          # the union
        out[name] = sorted(set(members))
    for name, lib in glob["libraries"].items():
        if name not in out:
            out[name] = sorted(set(lib))
    # Exactly what membersOf's "dtype" branch reads: the constructor table.
    for name, dt in api["datatypes"].items():
        members = [row[0] for row in dt.get("ctors", [])]
        members += [row[0] for row in dt.get("funcs", [])]
        members += [row[0] for row in dt.get("consts", [])]
        if members:
            out[name] = sorted(set(members))
    out["Enum"] = sorted(api["enums"].keys())
    return out


def lua_list(names):
    return "{" + ",".join('"%s"' % n.replace('"', '\\"') for n in names) + "}"


def write_probe(api, glob):
    exp = expected(api, glob)
    known = set(glob["executor"])
    known |= set(glob["libraries"].keys())
    known |= set(api["libraries"].keys())
    known |= set(api["datatypes"].keys())
    known |= set(api["enums"].keys())
    known |= {row[0] for row in api["globals"]["props"]}
    known |= {row[0] for row in api["globals"]["funcs"]}
    known |= {"game", "Game", "workspace", "Workspace", "script", "plugin",
              "shared", "_G", "_ENV", "self", "Enum", "Enums"}

    lines = []
    lines.append("-- Generated by tools/gen-apicheck.py. Do not edit.")
    lines.append("--")
    lines.append("-- Asks the engine what it actually has, so the editor's tables can be")
    lines.append("-- checked against it rather than against the documentation they came from.")
    lines.append("")
    lines.append("local EXPECTED = {")
    for ns in sorted(exp):
        lines.append('    ["%s"] = %s,' % (ns, lua_list(exp[ns])))
    lines.append("}")
    lines.append("")
    lines.append("local KNOWN_GLOBALS = {")
    for name in sorted(known):
        if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", name):
            lines.append('    ["%s"] = true,' % name)
    lines.append("}")
    lines.append("")
    lines.append(PROBE_BODY)
    open(PROBE, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    total = sum(len(v) for v in exp.values())
    print("gen-apicheck: %d namespaces, %d members, %d globals -> %s"
          % (len(exp), total, len(known), os.path.relpath(PROBE, ROOT)))


PROBE_BODY = r'''
-- ---------------------------------------------------------------- the probe

local function encode(value)
    local t = type(value)
    if t == "string" then
        return '"' .. value:gsub('[%c"\\]', function (c)
            if c == '"' then return '\\"' end
            if c == "\\" then return "\\\\" end
            return string.format("\\u%04x", string.byte(c))
        end) .. '"'
    end
    if t == "boolean" or t == "number" then return tostring(value) end
    if t == "table" then
        if #value > 0 or next(value) == nil then
            local parts = {}
            for i = 1, #value do parts[i] = encode(value[i]) end
            return "[" .. table.concat(parts, ",") .. "]"
        end
        local parts, keys = {}, {}
        for k in pairs(value) do keys[#keys + 1] = k end
        table.sort(keys)
        for _, k in ipairs(keys) do
            parts[#parts + 1] = encode(tostring(k)) .. ":" .. encode(value[k])
        end
        return "{" .. table.concat(parts, ",") .. "}"
    end
    return "null"
end

local result = { namespaces = {}, globals = {}, execglobals = {}, notes = {} }

-- What a bare name resolves to in this environment: the engine's globals plus
-- whatever the executor put there.
local function collectGlobals()
    local seen = {}
    local function take(into, env)
        if type(env) ~= "table" then return end
        local ok = pcall(function ()
            for k in pairs(env) do
                if type(k) == "string" and not seen[k] then
                    seen[k] = true
                    into[#into + 1] = k
                end
            end
        end)
        if not ok then result.notes[#result.notes + 1] = "enumeration failed" end
    end
    take(result.globals, getrenv and getrenv() or nil)
    take(result.globals, getfenv and getfenv(0) or nil)
    if getgenv then take(result.execglobals, getgenv()) end

    result.globalKinds = {}
    local env = (getrenv and getrenv()) or (getfenv and getfenv(0)) or {}
    for _, name in ipairs(result.globals) do
        local ok, v = pcall(function () return env[name] end)
        result.globalKinds[name] = (ok and type(v) == "function") and "f" or "p"
    end
end

-- Every namespace the editor's member check can be asked about. `pairs` is
-- tried first; a userdata-backed table answers nothing that way, so each
-- expected member is also probed by name.
local function collectNamespace(name, wanted)
    local ok, value = pcall(function () return getfenv(0)[name] end)
    if not ok or value == nil then
        local ok2, v2 = pcall(function () return loadstring("return " .. name)() end)
        if ok2 then value = v2 end
    end
    if value == nil then
        result.namespaces[name] = { present = false }
        return
    end

    local entry = { present = true, enumerated = {}, has = {}, enumerable = false }

    entry.kinds = {}
    pcall(function ()
        for k, v in pairs(value) do
            if type(k) == "string" then
                entry.enumerable = true
                entry.enumerated[#entry.enumerated + 1] = k
                -- What it is decides how the editor offers it: a function is
                -- called, a constant is not.
                entry.kinds[k] = (type(v) == "function") and "f" or "p"
            end
        end
    end)
    table.sort(entry.enumerated)

    for _, member in ipairs(wanted) do
        local got = pcall(function () return value[member] end)
        local exists = false
        if got then
            local ok3, v = pcall(function () return value[member] end)
            exists = ok3 and v ~= nil
        end
        entry.has[member] = exists
    end
    result.namespaces[name] = entry
end

collectGlobals()
for name, wanted in pairs(EXPECTED) do
    collectNamespace(name, wanted)
end

-- Which globals the editor would call unknown. This is the list that decides
-- whether anyone sees a squiggle under working code.
local unknown = {}
for _, name in ipairs(result.globals) do
    if not KNOWN_GLOBALS[name] and not name:match("^__nexa_") then
        unknown[#unknown + 1] = name
    end
end
for _, name in ipairs(result.execglobals) do
    if not KNOWN_GLOBALS[name] and not name:match("^__nexa_") then
        unknown[#unknown + 1] = name
    end
end
table.sort(unknown)
result.unknownGlobals = unknown

local json = encode(result)
local written = false
if writefile then
    local ok = pcall(writefile, "vanta-apicheck.json", json)
    written = ok
end

print("APICHECK globals=" .. #result.globals ..
      " exec=" .. #result.execglobals ..
      " namespaces=" .. (function () local n = 0 for _ in pairs(result.namespaces) do n = n + 1 end return n end)() ..
      " unknownGlobals=" .. #unknown ..
      " written=" .. tostring(written) ..
      " bytes=" .. #json)
for i = 1, math.min(#unknown, 40) do
    print("APICHECK unknown-global " .. unknown[i])
end
print("APICHECK done")
'''


def compare():
    api, glob = load_tables()
    exp = expected(api, glob)
    if not os.path.exists(ANSWER):
        sys.exit("no answer at %s — run ./tests/run.sh tests/apicheck.lua APICHECK" % ANSWER)
    answer = json.load(open(ANSWER, encoding="utf-8"))

    missing, extra, absent = [], [], []
    for ns, wanted in sorted(exp.items()):
        entry = answer["namespaces"].get(ns)
        if not entry or not entry.get("present"):
            absent.append(ns)
            continue
        has = entry.get("has", {})
        for member in wanted:
            if has.get(member) is False:
                extra.append("%s.%s" % (ns, member))
        if entry.get("enumerable"):
            for member in entry.get("enumerated", []):
                if member not in wanted:
                    missing.append("%s.%s" % (ns, member))

    print("== the engine has these, api.js does not (each one is a false positive) ==")
    print("\n".join("   " + m for m in missing) or "   none")
    print()
    print("== api.js has these, the engine does not (each one is a typo we would miss) ==")
    print("\n".join("   " + m for m in extra) or "   none")
    print()
    print("== namespaces the engine does not expose as a global at all ==")
    print("   " + ", ".join(absent) if absent else "   none")
    print()
    unknown = answer.get("unknownGlobals", [])
    print("== globals the engine defines that the editor would flag (%d) ==" % len(unknown))
    print("\n".join("   " + g for g in unknown) or "   none")


SNAPSHOT = os.path.join(ROOT, "tools", "engine-tables.json")

# The executor's own libraries come from this repository's source (gen-globals.py
# reads them); everything else in the answer is the engine's, and the engine is
# the only authority for it.
OURS = {"crypt", "cache", "base64", "http", "Drawing", "WebSocket", "Signal"}


def snapshot():
    """Write tools/engine-tables.json — what the engine said, for gen-api.py."""
    api, glob = load_tables()
    if not os.path.exists(ANSWER):
        sys.exit("no answer at %s — run the probe first" % ANSWER)
    answer = json.load(open(ANSWER, encoding="utf-8"))

    namespaces = {}
    for name, entry in sorted(answer["namespaces"].items()):
        if name in OURS or not entry.get("enumerable"):
            continue
        kinds = entry.get("kinds", {})
        members = {m: kinds.get(m, "p") for m in entry.get("enumerated", [])}
        if members:
            namespaces[name] = members

    ours = set(glob["executor"]) | set(glob["libraries"].keys())
    kinds = answer.get("globalKinds", {})
    globals_ = {name: kinds.get(name, "p")
                for name in answer.get("globals", [])
                if name not in ours and not name.startswith("__nexa_")}

    payload = {
        "_": [
            "What the engine actually has, captured by tests/apicheck.lua in a",
            "live game. gen-api.py merges it into api.js.",
            "",
            "The editor's library and datatype members otherwise come from",
            "Roblox's documentation, which is written by people and is not the",
            "engine: Vector3.max, Color3.toHSV, debug.dumpheap, SharedTable.*",
            "and BrickColor.New all exist and none of them are documented. A",
            "member that exists and is missing here becomes a squiggle under",
            "working code, so this file is the difference between a check people",
            "keep on and one they turn off.",
            "",
            "To refresh: python3 tools/gen-apicheck.py, run tests/apicheck.lua in",
            "a game, then python3 tools/gen-apicheck.py --snapshot.",
        ],
        "engine": answer.get("engine", "unknown"),
        "namespaces": namespaces,
        "globals": globals_,
    }
    with open(SNAPSHOT, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=1, sort_keys=True)
        f.write("\n")
    print("gen-apicheck: %d namespaces, %d members, %d globals -> %s"
          % (len(namespaces), sum(len(v) for v in namespaces.values()),
             len(globals_), os.path.relpath(SNAPSHOT, ROOT)))


if __name__ == "__main__":
    if "--compare" in sys.argv:
        compare()
    elif "--snapshot" in sys.argv:
        snapshot()
    else:
        api, glob = load_tables()
        write_probe(api, glob)
